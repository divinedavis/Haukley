"""Build the Roku package: resized art, catalog JSON, icons/splash, and the zip.

Reads scripts/catalog.json + scripts/rows.json and the art already generated by
make_posters.py (src/assets/titles). Roku caps packages at 4 MB, so art is
re-encoded at Roku display size. Output: roku/dist/Haukley-roku.zip

Usage: .venv/bin/python scripts/make_roku.py
"""
import json
import urllib.request
import shutil
import pathlib
import zipfile

from PIL import Image, ImageDraw

from make_posters import brand_card, draw_wordmark, wordmark_width

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROKU = ROOT / "roku"
ART = ROOT / "src" / "assets" / "titles"
IMG = ROKU / "images" / "titles"
MAX_ZIP = 4 * 1024 * 1024

POSTER = (240, 360)
CARD = (440, 248)
BACKDROP = (1280, 720)
STILL = (400, 225)


def save(src, dst, size, quality):
    dst.parent.mkdir(parents=True, exist_ok=True)
    Image.open(src).convert("RGB").resize(size, Image.LANCZOS).save(dst, quality=quality, optimize=True)


def stream_for(streams, tid, episode=0):
    # Same hash as streamFor() in src/catalog.ts.
    h = episode
    for c in tid:
        h = (h * 31 + ord(c)) % 1000003
    return streams[h % len(streams)]


def make_pill():
    """White 76px-tall pill as a Roku 9-patch (1px black stretch markers on top/left)."""
    w, h, ss = 80, 76, 4
    big = Image.new("RGBA", (w * ss, h * ss), (0, 0, 0, 0))
    ImageDraw.Draw(big).rounded_rectangle([0, 0, w * ss - 1, h * ss - 1], radius=h * ss // 2, fill=(255, 255, 255, 255))
    pill = big.resize((w, h), Image.LANCZOS)
    out = Image.new("RGBA", (w + 2, h + 2), (0, 0, 0, 0))
    out.paste(pill, (1, 1))
    for x in range(1 + h // 2 - 1, 1 + w - h // 2 + 1):
        out.putpixel((x, 0), (0, 0, 0, 255))
    for y in range(1 + h // 2 - 2, 1 + h // 2 + 2):
        out.putpixel((0, y), (0, 0, 0, 255))
    return out


def live(url):
    """True when the title's HLS master playlist is already on the CDN."""
    try:
        with urllib.request.urlopen(urllib.request.Request(url, method="HEAD"), timeout=15) as r:
            return r.status == 200
    except Exception:
        return False


def main():
    cat = json.loads((ROOT / "scripts" / "catalog.json").read_text())
    rows = json.loads((ROOT / "scripts" / "rows.json").read_text())
    ads = json.loads((ROOT / "scripts" / "ads.json").read_text())
    streams = rows["streams"]

    # Start from a clean image folder: only titles packaged below ship (4 MB cap).
    shutil.rmtree(IMG, ignore_errors=True)

    titles = {}
    for kind, key in (("movie", "movies"), ("show", "shows")):
        for t in cat[key]:
            tid = t["id"]
            src = ART / tid
            if not (src / "poster@2x.jpg").exists() or (t.get("stream") and not live(t["stream"])):
                continue  # art or video not ready yet (film still ingesting)
            save(src / "poster@2x.jpg", IMG / tid / "poster.jpg", POSTER, 70)
            save(src / "card@2x.jpg", IMG / tid / "card.jpg", CARD, 70)
            save(src / "backdrop@2x.jpg", IMG / tid / "backdrop.jpg", BACKDROP, 55)
            entry = {
                "id": tid, "kind": kind, "title": t["title"], "genre": t["genre"], "year": t["year"],
                "rating": t["rating"], "tagline": t["tagline"], "description": t["description"],
                "credits": t["credits"],
                "license": t.get("license") or "",
                "advisory": t.get("advisory") or "",
                "length": t.get("runtime") or f"{t['seasons']} Season{'s' if t['seasons'] != 1 else ''}",
                "poster": f"pkg:/images/titles/{tid}/poster.jpg",
                "card": f"pkg:/images/titles/{tid}/card.jpg",
                "backdrop": f"pkg:/images/titles/{tid}/backdrop.jpg",
                "stream": t.get("stream") or (t["episodes"][0]["stream"] if kind == "show" else stream_for(streams, tid)),
                # Side-loaded caption file (WebVTT/SRT URL) once real titles ship with one.
                "captions": t.get("captions", ""),
            }
            if kind == "show":
                eps = []
                for e in t["episodes"]:
                    n = e["number"]
                    save(src / f"ep{n}@2x.jpg", IMG / tid / f"ep{n}.jpg", STILL, 60)
                    eps.append({
                        "number": n, "name": e["name"], "minutes": e["minutes"], "summary": e["summary"],
                        "still": f"pkg:/images/titles/{tid}/ep{n}.jpg",
                        "stream": e["stream"],
                    })
                entry["episodes"] = eps
            titles[tid] = entry

    # Rows may name titles that aren't packaged (still ingesting): drop those, then empty rows.
    home = [{"key": "up-next", "title": "Up Next", "type": "upNext",
             "items": [{"id": u["id"], "label": u["label"], "progress": u["progress"], "episode": u.get("episode", 0)}
                       for u in rows["upNext"] if u["id"] in titles]}]
    home += [{"key": r["key"], "title": r["title"], "type": r["type"],
              "items": [{"id": i} for i in r["ids"] if i in titles]} for r in rows["home"]]
    home = [r for r in home if r["items"]]

    catalog = {"titles": titles, "rows": home, "ads": {k: ads[k] for k in ("adTagTemplate", "trackingUrl", "publishableKey")}}
    # Title artwork is served from haukley.com (the package has a 4 MB cap and the library keeps
    # growing); playback needs the network anyway, so the packaged fallback catalog points there too.
    remote = json.loads(json.dumps(catalog).replace("pkg:/images/titles/", "https://haukley.com/roku/img/"))
    (ROKU / "data").mkdir(parents=True, exist_ok=True)
    (ROKU / "data" / "catalog.json").write_text(json.dumps(remote, separators=(",", ":")))

    # Live copy for the app to fetch at launch (haukley.com/roku/catalog.json): same data with
    # artwork served from haukley.com, so new films reach Roku without a new package.
    web_img = ROOT / "web" / "roku" / "img"
    shutil.rmtree(web_img, ignore_errors=True)
    shutil.copytree(IMG, web_img)
    live_cat = json.loads(json.dumps(catalog).replace("pkg:/images/titles/", "https://haukley.com/roku/img/"))
    (ROOT / "web" / "roku" / "catalog.json").write_text(json.dumps(live_cat, separators=(",", ":")))

    make_pill().save(ROKU / "images" / "pill.9.png")

    # Channel store icon (FHD 540x405) and splash (1920x1080).
    brand_card((540, 405), 92).save(ROKU / "images" / "icon_fhd.png")
    brand_card((290, 218), 50).save(ROKU / "images" / "icon_hd.png")
    brand_card((1920, 1080), 200).save(ROKU / "images" / "splash_fhd.jpg", quality=80)
    # Header logo for the home screen (Roku labels can't color one character).
    logo = Image.new("RGBA", (int(wordmark_width(40)) + 8, 56), (0, 0, 0, 0))
    draw_wordmark(ImageDraw.Draw(logo), 0, 0, 40)
    logo.save(ROKU / "images" / "wordmark.png")

    dist = ROKU / "dist"
    dist.mkdir(exist_ok=True)
    out = dist / "Haukley-roku.zip"
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(ROKU.rglob("*")):
            rel = p.relative_to(ROKU)
            if rel.parts[:2] == ("images", "titles"):
                continue  # served from haukley.com/roku/img
            if p.is_file() and rel.parts[0] in ("manifest", "source", "components", "images", "data", "fonts"):
                z.write(p, rel.as_posix())
    size = out.stat().st_size
    print(f"{out} {size / 1024 / 1024:.2f} MB")
    if size > MAX_ZIP:
        raise SystemExit("Package is over Roku's 4 MB limit")


if __name__ == "__main__":
    main()
